-- B7b (owner, 23 November 2026: nothing a customer reads may say Synthetic). The second half of real-use file
-- 0022_sample_first_word.sql: a sample workspace may start its free text with "Sample " as well as "Synthetic ".
-- That file covers what the real-use module owns. This one covers what later modules own or fingerprint, which the
-- real-use file must not touch because those modules would then refuse to install on a fresh database:
--   this module's own three functions (the workspace name on creation and on rename, the workspace invitation label),
--   the participant command (invitation label and display label), once the programme lifecycle module has replaced it,
--   the participant label correction, billing and invoicing notes, and public programme page text, when installed,
--   the two CHECK constraints on the participant invitation label and display label, once the programme pages
--   module is installed, because that module fingerprints the constraints of those two tables before it installs.
-- "Synthetic " stays accepted everywhere, so every existing row and every caller that still sends it keeps working.
-- A real workspace is not affected: its branch of every check is unchanged. The minimum length of sample text stays 11.
--
-- The only change is the comparison  x LIKE 'Synthetic %'  becoming  x ~ '^(Synthetic|Sample) '. Owner, grants,
-- SECURITY DEFINER and search_path are kept by CREATE OR REPLACE, and each constraint keeps its name.
-- No row is read, rewritten or deleted: the two constraints are re-added NOT VALID, so new and changed rows are
-- checked as before and existing rows are not re-read (inside the installer's session the check would otherwise test
-- real workspaces' rows against the sample rule). No user, identity, principal, sign-in row, membership, workspace
-- or customer account is renamed, closed or removed.
--
-- The installer runs this file on every run (its name ends in _late), like file 0004, so a module installed after
-- this one is covered by the next run. Each item is a clean skip when it is not installed yet or already accepts
-- both words, is changed only when its live text is exactly the reviewed text (SHA-256) with the expected number of
-- comparisons, and stops the install when it is neither.
--
-- Rollback (additive, nothing to restore): a new numbered file that applies the reverse replacement,
--   '!~ ''^(Synthetic|Sample) ''' -> 'NOT LIKE ''Synthetic %''' and '~ ''^(Synthetic|Sample) ''' -> 'LIKE ''Synthetic %'''
-- for the functions and  '~ ''^(Synthetic|Sample) ''::text' -> '~~ ''Synthetic %''::text'  (again NOT VALID) for the
-- two constraints, and removing this file's name from the installer's repeat rule by not ending the new name in _late.
-- Rows written with "Sample " meanwhile stay as they are. Do not edit this file once applied (its hash is checked).
DO $sample$
DECLARE
 item text[];
 original text;
 updated text;
 found integer;
 old_like constant text:='LIKE ''Synthetic %''';
 old_not_like constant text:='NOT LIKE ''Synthetic %''';
 new_match constant text:='~ ''^(Synthetic|Sample) ''';
 new_not_match constant text:='!~ ''^(Synthetic|Sample) ''';
 two_words constant text:='''^(Synthetic|Sample) ''';
 old_check constant text:='~~ ''Synthetic %''::text';
 new_check constant text:='~ ''^(Synthetic|Sample) ''::text';
 relation regclass;
 registry regclass;
 ready boolean;
BEGIN
 -- signature, SHA-256 of the reviewed text, comparisons it holds, and the registry of the module that defines it last
 -- (empty: no wait). An item whose defining module is not installed yet is left for a later run.
 FOREACH item SLICE 1 IN ARRAY ARRAY[
  ['customer.provision_workspace(uuid,text)','71a30c7f4430458e6473fe103d0ce684efda0263832e0fb69742241c5a2c554a','1',''],
  ['customer.workspace_access_command(uuid,text,jsonb)','e429d532b2962680b450e0663893a365faffb6b07a849c99606f73985057ba38','1',''],
  ['customer.workspace_lifecycle_command(uuid,text,jsonb)','48e89d5ff1d7ac2840de41b3fd14b62aff2c74e8c3dc50e1899738d9e386d352','1',''],
  ['customer.programme_participant_command(uuid,text,jsonb)','e51c011b6da939ad792599089c9f817b3a5bee30878d3ac6e6da560f74e44d16','2','customer_programme_lifecycle_migrations.applied'],
  ['customer.programme_registration_label(uuid,uuid,integer,text)','adafbf3e3284d99315e7a4506d99868089b30944a3b53a244ebe940db6373314','1','customer_participant_label_migrations.applied'],
  ['customer_private.billing_synthetic_ok(text,integer)','7fc2570f27ec9f152f443e03c682ac64ead53fe768cc20d934940bfc161d8c86','1','customer_billing_migrations.applied'],
  ['customer.programme_application_command(uuid,text,jsonb)','1e2713761f2bcf11bd0c59ae91971f2e03462df4dc51a2052c72e50fc778bccf','2','customer_programme_publication_migrations.applied'],
  ['customer_private.programme_publication_copy_valid(jsonb,boolean)','992448e8baef3e2836023687f4e2b3c9730661d128cb772a6e95154b4b4fd755','2','customer_programme_publication_migrations.applied']
 ] LOOP
  IF item[4]<>'' THEN
   registry:=to_regclass(item[4]);
   ready:=false;
   IF registry IS NOT NULL THEN EXECUTE format('SELECT EXISTS(SELECT FROM %s)',registry) INTO ready; END IF;
   IF NOT ready THEN
    RAISE NOTICE 'Sample first word: % waits for its module, so it was left alone',item[1];
    CONTINUE;
   END IF;
  END IF;
  IF to_regprocedure(item[1]) IS NULL THEN
   RAISE NOTICE 'Sample first word: % is not installed, so it was left alone',item[1];
   CONTINUE;
  END IF;
  original:=pg_get_functiondef(item[1]::regprocedure);
  found:=(length(original)-length(replace(original,two_words,'')))/length(two_words);
  IF position('Synthetic %' IN original)=0 AND found=item[3]::integer THEN CONTINUE; END IF;
  IF encode(sha256(convert_to(original,'UTF8')),'hex')<>item[2] THEN
   RAISE EXCEPTION 'Sample first word prerequisite function differs: %. Review it and widen its first-word comparison',item[1];
  END IF;
  found:=(length(original)-length(replace(original,old_like,'')))/length(old_like);
  IF found<>item[3]::integer THEN RAISE EXCEPTION 'Sample first word comparison count differs: %',item[1]; END IF;
  updated:=replace(replace(original,old_not_like,new_not_match),old_like,new_match);
  IF position('Synthetic %' IN updated)>0
  OR (length(updated)-length(replace(updated,two_words,'')))/length(two_words)<>found THEN
   RAISE EXCEPTION 'Sample first word replacement differs: %',item[1];
  END IF;
  EXECUTE updated;
 END LOOP;

 -- The programme pages module refuses to install unless these two tables have a shape it was proven against, CHECK
 -- constraints included, so they are widened only after it is installed.
 registry:=to_regclass('customer_programme_publication_migrations.applied');
 ready:=false;
 IF registry IS NOT NULL THEN EXECUTE format('SELECT EXISTS(SELECT FROM %s)',registry) INTO ready; END IF;
 IF NOT ready THEN
  RAISE NOTICE 'Sample first word: the participant label checks wait for the programme pages module, so they were left alone';
  RETURN;
 END IF;
 FOREACH item SLICE 1 IN ARRAY ARRAY[
  ['customer_private.programme_invitation','programme_invitation_label_check'],
  ['customer_private.programme_registration','programme_registration_display_label_check']
 ] LOOP
  relation:=item[1]::regclass;
  SELECT pg_get_constraintdef(c.oid) INTO original FROM pg_constraint c
  WHERE c.conrelid=relation AND c.conname=item[2] AND c.contype='c';
  IF original IS NULL THEN RAISE EXCEPTION 'Sample first word constraint is missing: %.%',item[1],item[2]; END IF;
  IF position('Synthetic %' IN original)=0 AND position(new_check IN original)>0 THEN CONTINUE; END IF;
  IF (length(original)-length(replace(original,old_check,'')))/length(old_check)<>1 THEN
   RAISE EXCEPTION 'Sample first word constraint differs: %.%',item[1],item[2];
  END IF;
  updated:=replace(replace(original,old_check,new_check),' NOT VALID','');
  IF position('Synthetic %' IN updated)>0 THEN
   RAISE EXCEPTION 'Sample first word constraint replacement differs: %.%',item[1],item[2];
  END IF;
  EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I',relation,item[2]);
  EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I %s NOT VALID',relation,item[2],updated);
 END LOOP;
END $sample$;
