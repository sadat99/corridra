#!/usr/bin/env bash
# Shared audit preview: serve.sh [on|off]  (on = CORRIDRA_UX_TEAM_DESK_V41 true; off = unset). Foreground; Ctrl-C/SIGTERM stops.
set -euo pipefail
MODE="${1:-on}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
cd "$REPO"
for f in SHELLS_V2 ROAD OPERATOR_URLS MOVE NAV MISSIONS_V2 LENSES BEFORE_SEND ACCESS_DOORS TRIP PROGRAMME POCKET FIRSTQ FRONT_DOORS FAIRS BUYER_STEPS MOVE_RECORDS BOOKS; do
  export "CORRIDRA_UX_$f=true"
done
unset CORRIDRA_UX_OPERATOR_DESK CORRIDRA_UX_JOURNEY_MODES CORRIDRA_UX_TEAM_DESK_V41
case "$MODE" in on) export CORRIDRA_UX_TEAM_DESK_V41=true ;; off) ;; *) echo "usage: serve.sh [on|off]" >&2; exit 2 ;; esac
export CORRIDRA_LANGUAGES_PREVIEW=true CORRIDRA_SUPPLY_SOURCES=true
# Switches that close fixture gaps (routes answer 404/503 without them).
export CORRIDRA_TEAM_INVITES=true CORRIDRA_ROUTE_PACK_FORM=true CORRIDRA_AI_CONNECT_FORM=true
export CORRIDRA_HELPER_INTEREST=true CORRIDRA_REPLY_PAGE=true CORRIDRA_PROGRAMME_PAGES=true CORRIDRA_SOURCING_WORKFLOW=true
export CORRIDRA_CUSTOMER_OPEN_ADMISSION=synthetic-only
for n in WORKSPACES COMPANIES SAVED_MISSIONS DECISIONS DELIVERY REQUESTS REQUEST_DETAILS ORGANISATION_PROFILES MISSION_DRAFTS \
  PROGRAMMES PARTICIPANTS PROGRAMME_CONTEXT PROGRAMME_ECONOMICS PROGRAMME_COORDINATION PROGRAMME_TEMPLATES PROGRAMME_PRICING \
  PROGRAMME_TERMS PROGRAMME_PROJECTIONS MISSION_SHARES MEMBER_ROLES ORGANISATION_LINKS SERVICE_REQUESTS \
  SPECIFICATION_CONFIRMATION BILLING INVOICING SIMULATED_PAYMENTS ACCOUNT_LIFECYCLE WORKSPACE_LIFECYCLE; do
  export "CORRIDRA_CUSTOMER_${n}_ENABLED=true"
done
unset VERCEL_ENV CORRIDRA_REAL_USE_ENABLED CORRIDRA_LIVE_ROLLOUT_ENABLED HELPER_INTEREST_FIXTURE
# Synthetic customers for the test sign-in stand-in: made up once, reused across restarts so saved cookies stay valid.
export AUDIT_REPO="$REPO" AUDIT_CUSTOMERS_FILE="$HERE/customers.json"
[ -f "$AUDIT_CUSTOMERS_FILE" ] || node "$HERE/make-customers.mjs" "$AUDIT_CUSTOMERS_FILE"
export NODE_OPTIONS="${NODE_OPTIONS:-} --import=file://$HERE/preload.mjs"
echo "$MODE" > "$HERE/mode"
exec pnpm exec tsx scripts/operator-browser-server.ts
